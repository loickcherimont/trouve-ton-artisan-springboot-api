package com.github.loickcherimont.trouve_ton_artisan.service;

import java.util.List;

import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import com.github.loickcherimont.trouve_ton_artisan.dto.CategoryResponse;
import com.github.loickcherimont.trouve_ton_artisan.repository.CategoryRepository;

import lombok.RequiredArgsConstructor;

/**
 * Business logic for reading professional categories.
 *
 * <p>This service is the boundary between the persistence layer and the
 * web layer: it fetches {@code Category} entities and exposes them as
 * immutable {@link CategoryResponse} DTOs.</p>
 *
 * <p>Dependencies are injected through the constructor, generated by
 * Lombok {@code @RequiredArgsConstructor} from the final fields below.</p>
 */
@Service
@Transactional(readOnly = true)
@RequiredArgsConstructor
public class CategoryService {

	private final CategoryRepository categoryRepository;

	/**
	 * Returns every category, ordered by the database default order.
	 *
	 * @return the list of all categories as DTOs; empty list if none exist
	 */
	public List<CategoryResponse> findAll() {
		return categoryRepository.findAll().stream()
				.map(CategoryResponse::from)
				.toList();
	}

}
