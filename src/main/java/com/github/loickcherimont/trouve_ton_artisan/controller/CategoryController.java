package com.github.loickcherimont.trouve_ton_artisan.controller;

import java.util.List;

import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.github.loickcherimont.trouve_ton_artisan.dto.CategoryResponse;
import com.github.loickcherimont.trouve_ton_artisan.service.CategoryService;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;

/**
 * Public REST controller exposing the professional categories.
 *
 * <p>All endpoints return DTOs only — JPA entities never leave this layer.</p>
 *
 * <p>Dependencies are injected through the constructor, generated by
 * Lombok {@code @RequiredArgsConstructor} from the final fields below.</p>
 */
@RestController
@RequestMapping("/api/categories")
@Tag(name = "Categories", description = "Consultation of professional categories")
@RequiredArgsConstructor
public class CategoryController {

	private final CategoryService categoryService;

	/**
	 * Returns the full list of professional categories.
	 *
	 * <p>Example response:</p>
	 * <pre>{@code
	 * [
	 *   { "id": 1, "name": "Bâtiment", "slug": "batiment" }
	 * ]
	 * }</pre>
	 *
	 * @return HTTP 200 with the list of categories, or an empty list
	 */
	@Operation(
			summary = "List all professional categories",
			description = "Returns every craftsman category with its id, name and slug. "
					+ "The list is empty when no category exists.")
	@GetMapping
	public ResponseEntity<List<CategoryResponse>> findAll() {
		return ResponseEntity.ok(categoryService.findAll());
	}

}
